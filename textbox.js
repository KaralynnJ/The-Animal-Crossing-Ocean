const dialogBox = document.createElement("div");
dialogBox.id = "blathers-dialog";
dialogBox.innerHTML = `
  <div class="blathers-portrait">
    <img src="assets/blathers.png" alt="Blathers" onerror="this.style.display='none'; this.parentElement.classList.add('no-img')" />
  </div>
  <div class="blathers-content">
    <div class="blathers-name">Blathers</div>
    <div class="blathers-text"></div>
  </div>
  <div class="blathers-advance">&#9660;</div>
`;
document.body.appendChild(dialogBox);

let currentLines = [];
let currentIndex = 0;
let isAnimating = false;
let animationFrame = null;
let fullText = "";
let displayedChars = 0;

const textEl = dialogBox.querySelector(".blathers-text");
const advanceEl = dialogBox.querySelector(".blathers-advance");

function showChar() {
  if (displayedChars < fullText.length) {
    displayedChars++;
    textEl.textContent = fullText.slice(0, displayedChars);
    animationFrame = setTimeout(showChar, 22);
  } else {
    isAnimating = false;
    advanceEl.classList.add("visible");
  }
}

function showLine(text) {
  if (animationFrame) clearTimeout(animationFrame);
  fullText = text;
  displayedChars = 0;
  isAnimating = true;
  advanceEl.classList.remove("visible");
  textEl.textContent = "";
  showChar();
}

function openDialog(key) {
  const lines = blathersDialog[key];
  if (!lines) return;
  currentLines = lines;
  currentIndex = 0;
  dialogBox.classList.add("visible");
  showLine(lines[0]);
}

function advanceDialog() {
  if (isAnimating) {
    clearTimeout(animationFrame);
    isAnimating = false;
    textEl.textContent = fullText;
    advanceEl.classList.add("visible");
    return;
  }
  currentIndex++;
  if (currentIndex < currentLines.length) {
    showLine(currentLines[currentIndex]);
  } else {
    closeDialog();
  }
}

function closeDialog() {
  dialogBox.classList.remove("visible");
  if (animationFrame) clearTimeout(animationFrame);
  currentLines = [];
  currentIndex = 0;
}

dialogBox.addEventListener("click", advanceDialog);

document.addEventListener("keydown", (e) => {
  if (e.key === "Enter" || e.key === " " || e.key === "ArrowRight") {
    if (dialogBox.classList.contains("visible")) {
      e.preventDefault();
      advanceDialog();
    }
  } else if (e.key === "Escape") {
    closeDialog();
  }
});

document.querySelectorAll(".creature-wrapper").forEach((wrapper) => {
  const classes = Array.from(wrapper.classList);
  const key = classes.find((c) => c !== "creature-wrapper");
  if (!key) return;

  wrapper.addEventListener("click", (e) => {
    e.stopPropagation();
    openDialog(key);
  });
});

document.addEventListener("click", (e) => {
  if (!dialogBox.contains(e.target)) {
    closeDialog();
  }
});
